"""Add a spoken narration to the demo video -> docs/demo/pipeline_demo_narrated.mp4.

One passage per animation step, spoken by a free hosted voice (Fish Audio via OpenRouter)
over the music track turned down. The service picks a new speaker for every request unless
it is given a voice to imitate, so every request carries docs/demo/voice/reference.wav (a
clip it generated itself) and all passages come out in that one voice. Each passage starts LEAD seconds after its caption
appears; step timings and captions are read from the page itself, so the voice cannot
drift from the picture. The run stops if a passage would run into the next caption, if a
passage says a number its caption does not show, or if the key's usage total moves at all
(the model is free; this is the proof). Clips are kept in docs/demo/voice/ and only
requested again when their text changes.

Run: conda run -n xai python scripts/make_demo_voice.py      (after make_demo_music.py)
"""
from __future__ import annotations
import base64, hashlib, html, json, os, re, subprocess
from pathlib import Path
import requests
from dotenv import load_dotenv

ROOT = Path(__file__).resolve().parents[1]
DEMO = ROOT / "docs" / "demo"
PAGE, MUSIC, OUT, CLIPS = DEMO / "pipeline_demo.html", DEMO / "pipeline_demo_music.mp4", DEMO / "pipeline_demo_narrated.mp4", DEMO / "voice"
CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
API, MODEL = "https://openrouter.ai/api/v1", "fish-audio/s2.1-pro-free:free"
REF, REF_TEXT = CLIPS / "reference.wav", "Those sources become 7 documents, in 6 categories. Together, they form the knowledge base."
TONE = "enthusiastic and warm, like explaining to a curious friend"
LEAD, MUSIC_DB, VOICE_DB = .3, -18, 0   # seconds after the caption appears; music and voice gain
# One passage per step, in step order. Numbers are written as on screen (checked below).
NARRATION = [
    "This is everything the detector tells you. Just four lines.",
    "No device. No consequence. No idea what to do next.",
    "So where does the missing knowledge come from? Standards, a dataset, a textbook and a grid model.",
    "Those sources become 7 documents, in 6 categories. Together, they form the knowledge base.",
    "Most are paraphrased. One is generated by a script. And one, we wrote ourselves.",
    "That's 26,407 characters, in 9 chunks.",
    "One chunk holds the row for RTU-2: 10.0.0.3.",
    "Next, a small language model reads every chunk, and pulls out the relations it finds.",
    "It misses some grid facts. So we add them ourselves: 7 one-line facts from the asset table.",
    "The result: 153 nodes and 134 edges. But notice: separate islands, not one web.",
    "Now a flow arrives at that same address, port 2404.",
    "The random-forest detector flags it: attack, confidence 1.00.",
    "But why? SHAP shows us which features of the flow pushed the detector toward that decision.",
    "Zero-length packets. Almost no gap between them. But we still don't know which device.",
    "Step 1. A table lookup turns the IP address into a device. No language model needed.",
    "Step 2. The alert and the SHAP evidence are attached, exactly as they are.",
    "Step 3. LightRAG searches the knowledge graph, and retrieves the entries closest to the regulator's question.",
    "Remember, the device and the regulation sit on separate islands. This is where they are finally joined.",
    "Now, the answers. The operator learns which breakers to check, and what to do next.",
    "The data scientist learns what the features prove and, just as important, what they cannot.",
    "And the regulator gets the reporting clock, and who needs to be notified.",
    "And here is the key point: every highlighted phrase traces back to a source.",
    "Four lines in. Three answers out, each one traceable.",
]
# ponytail: spellings for terms a voice would misread; anything not listed is read as written
SAY_AS = {"10.0.0.3": "ten dot zero dot zero dot three", "2404": "twenty-four oh four", "1.00": "one point zero zero",
          "RTU-2": "R T U two", "SHAP": "shap", "LightRAG": "Light Rag"}
numbers = lambda s: set(re.findall(r"\d[\d.,]*\d|\d", s))


def main() -> None:
    load_dotenv(ROOT / ".env")
    auth = {"Authorization": f"Bearer {os.environ['OPENROUTER_API_KEY']}"}

    def usage() -> float:
        r = requests.get(f"{API}/key", headers=auth, timeout=30)
        r.raise_for_status()
        return r.json()["data"]["usage"]

    dom = subprocess.run([CHROME, "--headless=new", "--dump-dom", PAGE.as_uri()],
                         capture_output=True, text=True, check=True).stdout
    found = re.search(r'data-beats="([^"]*)"', dom)
    assert found, "the page did not expose its step table (is docs/demo/demo_data.js there?)"
    beats = json.loads(html.unescape(found.group(1)))   # [seconds, rail stage, caption]
    assert len(beats) == len(NARRATION), f"{len(beats)} steps on the page but {len(NARRATION)} passages here"

    reference = [{"type": "input_audio", "input_audio": {"data": "data:audio/wav;base64," + base64.b64encode(REF.read_bytes()).decode()}},
                 {"type": "text", "text": REF_TEXT}]
    spent_before = usage()
    cmd, chain, start = ["ffmpeg", "-loglevel", "error", "-y", "-i", str(MUSIC)], [f"[0:a]volume={MUSIC_DB}dB[m]"], 0
    print(f"{'starts':>7} {'speech':>7} {'spare':>6}  passage")
    for i, ((dur, _, caption), passage) in enumerate(zip(beats, NARRATION), 1):
        assert numbers(passage) <= numbers(caption), f"step {i} says {numbers(passage) - numbers(caption)}, not on screen: {caption}"
        text = passage
        for written, spoken in SAY_AS.items():
            text = text.replace(written, spoken)
        clip = CLIPS / f"{i:02d}_{hashlib.sha1((MODEL + TONE + REF_TEXT + text).encode()).hexdigest()[:8]}.mp3"
        if not clip.exists():
            r = requests.post(f"{API}/audio/speech", headers=auth, timeout=180,
                              json={"model": MODEL, "input": text, "instructions": TONE, "response_format": "mp3",
                                    "input_references": reference})
            if r.status_code != 200:
                raise SystemExit(f"step {i}: speech request failed ({r.status_code}): {r.text[:300]}")
            clip.write_bytes(r.content)
            assert usage() == spent_before, f"step {i}: the key's usage total moved; {MODEL} is no longer free, stopping"
        speech = float(subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0",
                                       str(clip)], capture_output=True, text=True, check=True).stdout)
        spare = dur - LEAD - speech
        print(f"{start + LEAD:7.1f} {speech:7.1f} {spare:6.1f}  {passage}")
        assert spare > .5, f"step {i}: the passage takes {speech:.1f} s but the caption is up for {dur} s ({clip.name})"
        cmd += ["-i", str(clip)]
        chain.append(f"[{i}:a]adelay={round((start + LEAD) * 1000)}:all=1,volume={VOICE_DB}dB[v{i}]")
        start += dur
    mix = "[m]" + "".join(f"[v{i}]" for i in range(1, len(beats) + 1))
    chain.append(f"{mix}amix=inputs={len(beats) + 1}:normalize=0:duration=first[a]")
    subprocess.run(cmd + ["-filter_complex", ";".join(chain), "-map", "0:v", "-map", "[a]", "-c:v", "copy",
                          "-c:a", "aac", "-b:a", "192k", "-movflags", "+faststart", str(OUT)], check=True)
    print(f"{len(beats)} passages, key usage unchanged at {spent_before} -> {OUT.name} ({OUT.stat().st_size / 1e6:.1f} MB)")


if __name__ == "__main__":
    main()
